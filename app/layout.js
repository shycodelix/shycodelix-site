// ---------------------------------------------------------------------------
// Single source of truth for the share-card PNGs
// ---------------------------------------------------------------------------
// The card PNGs that the case-study pages point their og:image at are NOT the
// extensionless form Next emits (/work/<slug>/opengraph-image). They live at
// public/og/<slug>.png and are generated by:
//   1. app/work/<slug>/opengraph-image.js  (the Ink source)
//   2. scripts/og-sync.mjs                  (build -> copy into public/og)
//
// To regenerate after any card edit:
//     npm run build && node scripts/og-sync.mjs
//
// The generated files are committed so the same PNG is served from every host
// (Freebuff worker, Vercel static export, and the owned domain once this branch
// is on main). The only thing that can make them stale is running the two commands
// above and forgetting to commit the result, or pointing openGraph.images at a
// URL that no host serves. Both are caught by the build+check in this repo.
//
// The same slug list drives the serving-side Worker regex in sites-static/serve.js
// (isPublicPngCard) and the og-sync copy mapping, so a committed card that is not
// in that list can never be served, and a served card that does not exist in
// public/og is caught by og-sync before deploy.
// ---------------------------------------------------------------------------

